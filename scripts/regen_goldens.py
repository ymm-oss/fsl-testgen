"""Regenerate tests/golden from an `fslc` binary of ymm-oss/fsl.

    scripts/regen_goldens.py --fslc PATH/TO/fslc --fsl-root PATH/TO/fsl

For every case this writes `input.json` (the bytes `fslc testgen-input`
prints), one expected file per target and unwired mode (the bytes
`fslc testgen --target T [--allow-unwired]` prints), and `case.json`.
A refusal is recorded as `<target>[.unwired].error` with the message.

The tests only read these files. The one edit made to fslc's bytes: a
generated file that embeds the absolute path of the spec has the directory
the command ran in replaced by `/SPEC_ROOT`, so the goldens do not depend on
where they were generated; the tests pass the same spelling as --spec-path.
"""

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

TARGETS = ["pytest", "vitest", "swift", "kotlin", "dart", "phpunit"]
# Targets whose bytes are taken from `fslc testgen`. A target that has
# deliberately left byte identity is generated by fsl-testgen itself; see
# CONTRIBUTING.md.
FROZEN_TARGETS = TARGETS
SPEC_ROOT = "/SPEC_ROOT"

LITERALS_SPEC = """spec Literals {
  type N = 0..1
  state { x: Int }
  init { x = 0 }
  action set(v: N) { x = v }
  reachable One { x == 1 }
}
"""

# name, description, spec relative to the fsl checkout (or None for a spec
# written here), depth
CASES = [
    ("kernel", "a kernel-dialect spec", "specs/cart_v1.fsl"),
    ("requirements", "a requirements document with acceptance scenarios",
     "examples/self/monitor_action_boundary.fsl"),
    ("forbidden", "a requirements document with a forbidden scenario",
     "examples/gallery/valid/small_forbidden_guarded_cancel.fsl"),
    ("business", "a business document with leadsTo and reachable scenarios",
     "examples/layers/return_policy.fsl"),
    ("db", "a db document", "examples/db/safe_rollback_equivalence.fsl"),
    ("compose", "a compose root: kernel is null and walk order differs from state",
     "specs/bank_system.fsl"),
    ("domain", "a domain document (generic stage, no domain post-processing)",
     "examples/domain/order_functional_ddd.fsl"),
    ("governance", "a governance document: no scenarios, an empty walk, and a "
     "Kernel whose spans break kernel.v1", "examples/consulting/governance_controls.fsl"),
]
DEPTH = "3"


def run(fslc, cwd, args):
    return subprocess.run([str(fslc), *args], cwd=cwd, capture_output=True, check=False)


def expected_files(fslc, cwd, spec, output=None, targets=FROZEN_TARGETS):
    """{file name: bytes} for every frozen target and unwired mode."""
    files = {}
    for target in targets:
        for suffix, flags in (("", []), (".unwired", ["--allow-unwired"])):
            args = ["testgen", spec, "--depth", DEPTH, "--target", target, *flags]
            if output is not None:
                out = pathlib.Path(cwd) / output
                out.parent.mkdir(parents=True, exist_ok=True)
                if out.exists():
                    out.unlink()
                args += ["-o", output]
            done = run(fslc, cwd, args)
            name = f"{target}{suffix}"
            if done.returncode == 0:
                files[name] = out.read_bytes() if output is not None else done.stdout
            elif done.returncode == 2:
                envelope = json.loads(done.stdout)
                files[f"{name}.error"] = (envelope["message"] + "\n").encode()
            else:
                sys.exit(f"{spec} --target {target} {flags}: exit {done.returncode}\n"
                         f"{done.stdout.decode()}{done.stderr.decode()}")
    return files


def write_case(golden, name, description, fslc, cwd, spec, output=None):
    done = run(fslc, cwd, ["testgen-input", spec, "--depth", DEPTH])
    if done.returncode != 0:
        sys.exit(f"{name}: fslc testgen-input {spec} exit {done.returncode}\n"
                 f"{done.stdout.decode()}")
    directory = golden / name
    directory.mkdir(parents=True)
    (directory / "input.json").write_bytes(done.stdout)
    root = str(pathlib.Path(cwd).resolve())
    if not re.fullmatch(r"[A-Za-z0-9/_.\-]+", root):
        sys.exit(f"{root}: a directory name that a generated file would escape")
    for file_name, content in expected_files(fslc, cwd, spec, output).items():
        content = content.replace(root.encode(), SPEC_ROOT.encode())
        (directory / file_name).write_bytes(content)
    case = {
        "description": description,
        "spec": spec,
        "depth": int(DEPTH),
        "spec_path": f"{SPEC_ROOT}/{spec}",
    }
    if output is not None:
        case["output"] = output
    (directory / "case.json").write_text(json.dumps(case, indent=2) + "\n")
    for path in directory.iterdir():
        if root.encode() in path.read_bytes():
            sys.exit(f"{path}: still names the directory it was generated in")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fslc", required=True, type=pathlib.Path)
    parser.add_argument("--fsl-root", required=True, type=pathlib.Path)
    parser.add_argument("--golden", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parent.parent / "tests/golden")
    arguments = parser.parse_args()
    fslc = arguments.fslc.resolve()
    golden = arguments.golden
    if golden.exists():
        shutil.rmtree(golden)
    golden.mkdir(parents=True)
    for name, description, spec in CASES:
        write_case(golden, name, description, fslc, arguments.fsl_root.resolve(), spec)
    with tempfile.TemporaryDirectory(prefix="fsl-testgen-golden-") as scratch:
        scratch = pathlib.Path(scratch).resolve()
        weird = "we'ird*na>me?.fsl"
        (scratch / weird).write_text(LITERALS_SPEC)
        write_case(golden, "escaped-name",
                   "a file name every header has to escape", fslc, scratch, weird)
        (scratch / "specs").mkdir()
        (scratch / "specs/literals.fsl").write_text(LITERALS_SPEC)
        write_case(golden, "output", "written with -o: the spec path is relative to the output",
                   fslc, scratch, "specs/literals.fsl", output="generated/nested/conformance.out")
    print(f"wrote {len(CASES) + 2} cases to {golden}")


if __name__ == "__main__":
    main()
